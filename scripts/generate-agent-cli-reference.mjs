import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { format } from "prettier";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
if (process.argv.slice(2).some((arg) => arg !== "--check"))
  throw new Error("Only --check is supported");
const cargo = [
  "run",
  "--quiet",
  "--locked",
  "-p",
  "memoka-desktop",
  "--bin",
  "memoka-cli",
  "--",
];
const cli = (...args) =>
  execFileSync("cargo", [...cargo, ...args], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 4 * 1024 * 1024,
  });
const contract = JSON.parse(cli("edit-schema", "--format", "json"));
const configContract = JSON.parse(cli("config", "schema", "--format", "json"));
const help = cli("--help").trim();
const directory = path.join(root, "skills", "memoka", "references");
const schema = await format(JSON.stringify(contract, null, 2), {
  parser: "json",
});
const markdown = await format(
  [
    "# Memoka CLI reference",
    "",
    "Generated by `corepack pnpm agent:reference` from the CLI parser help and Rust editing DTOs. Do not edit this file by hand.",
    "",
    `CLI version: \`${contract.cli_version}\`. Editing protocol: \`${contract.schema_version}\`.`,
    "",
    "## Commands",
    "",
    "```text",
    help,
    "```",
    "",
    "## Editing contract",
    "",
    "Read device synchronization with `memoka-cli sync status --workspace PATH --format json`. Read operations never start networking. Revision and edit receipts are local to a Workspace copy. In synchronization-enabled Workspaces, include the `replica_id` from this copy’s edit descriptor in every edit, Note or Section request. Requests from another Replica are rejected before receipt lookup; retry the identical request only on its original Replica. A restored backup opens with a new Replica and synchronization disabled.",
    "",
    "The machine-readable contract is [edit-schema.json](edit-schema.json). The installed CLI can return it with `memoka-cli edit-schema --format json`.",
    "",
    "```json",
    JSON.stringify(contract, null, 2),
    "```",
    "",
    "## Application settings",
    "",
    "Application-wide settings do not take --workspace. Get the current path, effective values and revision with `memoka-cli config get --format json`. The generated contract is [config-schema.json](config-schema.json); query the installed CLI with `memoka-cli config schema --format json`.",
    "",
    "Use `config set --input FILE --dry-run --format json` before applying that file. On CONFIG_CONFLICT reread and reconsider the change. Settings use absolute assignments plus compare-and-swap, not Note editing receipts or request IDs. After an uncertain response, read back the configuration; do not overwrite a newer revision.",
    "",
  ].join("\n"),
  { parser: "markdown" },
);
for (const [name, expected] of [
  ["cli.md", markdown],
  ["edit-schema.json", schema],
  [
    "config-schema.json",
    await format(JSON.stringify(configContract, null, 2), { parser: "json" }),
  ],
]) {
  const destination = path.join(directory, name);
  if (check) {
    const actual = await readFile(destination, "utf8").catch(() => null);
    if (actual !== expected)
      throw new Error(`${name} is stale; run corepack pnpm agent:reference`);
  } else {
    await mkdir(directory, { recursive: true });
    await writeFile(destination, expected);
  }
}
process.stdout.write(
  check
    ? "Agent CLI reference is current.\n"
    : "Generated Agent CLI reference.\n",
);
